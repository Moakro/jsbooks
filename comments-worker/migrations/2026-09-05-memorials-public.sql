-- 기념일을 전체 공개로 맞춘다 — 코드가 이미 그렇게 정해 둔 상태에 데이터를 맞추는 보정.
--
-- worker 의 normalizeEventInput 은 "기념일: 항상 전체 공개 (증산교단 연례 기념일 등).
-- is_public 입력 무시하고 1 로 강제" 한다. 그러나 그 규칙은 2026-05-26(#114)에
-- 들어왔고, **그 전에 만들어진 기념일은 is_public=0 으로 남아 있다.**
--
-- 목록 API 가 비로그인에게 is_public=1 만 주도록 열렸으므로(같은 PR), 이 보정이
-- 없으면 옛 기념일은 로그인해야만 보이는 상태 그대로다 — 고친 것이 눈에 보이지 않는다.
--
-- 대상은 category='기념일' 인 행뿐이다. '일정'·'기타' 는 글쓴이가 공개 여부를
-- 직접 고르는 것이라 건드리지 않는다. 개인 일정을 임의로 공개로 바꾸는 일은 없다.
UPDATE events
   SET is_public = 1,
       updated_at = datetime('now')
 WHERE category = '기념일'
   AND is_public = 0;
